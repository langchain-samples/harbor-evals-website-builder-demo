"""Copy the shared verifier modules into every task's tests/ directory.

Harbor uploads each task's `tests/` folder into the trial container on its
own, so a verifier can only import what sits beside it. `sitecheck.py` and
`_shared/harness.py` are therefore vendored into each task rather than
imported from the project root.

They are copies of one source of truth, not files to edit in place. Run this
after changing either:

    python evals/sync.py

`--check` exits non-zero if any copy is stale, for a pre-flight before a job.
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

EVALS = Path(__file__).parent
PROJECT = EVALS.parent
BANNER = "# Generated by evals/sync.py — edit the source, not this copy.\n"

SOURCES = {
    "sitecheck.py": PROJECT / "deep-agent" / "sitecheck.py",
    "harness.py": EVALS / "_shared" / "harness.py",
}


def tasks() -> list[Path]:
    """Every direct child of evals/ that looks like a Harbor task."""
    return sorted(p for p in EVALS.iterdir() if (p / "task.toml").is_file())


def main() -> int:
    check_only = "--check" in sys.argv
    stale: list[str] = []

    for name, source in SOURCES.items():
        if not source.is_file():
            print(f"missing source: {source}")
            return 2
        wanted = BANNER + source.read_text(encoding="utf-8")
        for task in tasks():
            target = task / "tests" / name
            current = target.read_text(encoding="utf-8") if target.is_file() else None
            if current == wanted:
                continue
            stale.append(f"{task.name}/tests/{name}")
            if not check_only:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(wanted, encoding="utf-8")

    if check_only:
        if stale:
            print("stale copies — run `python evals/sync.py`:")
            print("\n".join(f"  {s}" for s in stale))
            return 1
        print(f"up to date across {len(tasks())} task(s)")
        return 0

    print(f"synced {len(SOURCES)} module(s) into {len(tasks())} task(s)")
    if stale:
        print("updated:")
        print("\n".join(f"  {s}" for s in stale))
    return 0


if __name__ == "__main__":
    sys.exit(main())
