"""Vendor the shared verifier into every task's tests/ directory.

Harbor uploads each task's `tests/` folder on its own, so a verifier can only
import what sits beside it. `_shared/functional.py` is therefore copied into
each task rather than imported from a parent.

They are generated copies. Edit `_shared/functional.py`, then:

    python dataset/sync.py            # copy into every task
    python dataset/sync.py --check    # non-zero if any copy is stale
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

DATASET = Path(__file__).resolve().parent
BANNER = "# Generated by dataset/sync.py — edit _shared/functional.py, not this copy.\n"
SOURCES = {"functional.py": DATASET / "_shared" / "functional.py"}


def tasks() -> list[Path]:
    return sorted(p for p in DATASET.iterdir() if (p / "task.toml").is_file())


def main() -> int:
    check_only = "--check" in sys.argv
    stale: list[str] = []
    for name, source in SOURCES.items():
        if not source.is_file():
            print(f"missing source: {source}")
            return 2
        wanted = BANNER + source.read_text(encoding="utf-8")
        for task in tasks():
            target = task / "tests" / name
            if target.is_file() and target.read_text(encoding="utf-8") == wanted:
                continue
            stale.append(f"{task.name}/tests/{name}")
            if not check_only:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(wanted, encoding="utf-8")

    if check_only:
        if stale:
            print("stale — run `python dataset/sync.py`:")
            print("\n".join(f"  {s}" for s in stale))
            return 1
        print(f"in sync across {len(tasks())} task(s)")
        return 0
    print(f"synced into {len(tasks())} task(s)" + (f"; updated {len(stale)}" if stale else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
